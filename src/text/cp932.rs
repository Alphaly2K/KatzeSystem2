pub(super) fn user_defined(unit: u16) -> u16 {
    let offset = unit - 0xe000;
    let lead = 0xf0 + offset / 188;
    let trail = offset % 188 + 0x40;
    (lead << 8) | (trail + u16::from(trail >= 0x7f))
}

pub(crate) fn encode_replacing(source: &[u16]) -> Vec<u8> {
    let mut output = Vec::new();
    for &unit in source.iter().take_while(|&&unit| unit != 0) {
        let mapped = if (0xe000..=0xe757).contains(&unit) {
            Some(user_defined(unit))
        } else {
            BEST_FIT
                .binary_search_by_key(&unit, |&(key, _)| key)
                .ok()
                .map(|index| BEST_FIT[index].1)
        };
        if let Some(value) = mapped {
            if value > 255 {
                output.push((value >> 8) as u8);
            }
            output.push(value as u8);
        } else if let Some(character) = char::from_u32(u32::from(unit)) {
            match super::cp932_encoded(&character.to_string()) {
                Ok(bytes) => output.extend(bytes),
                Err(_) => output.push(b'?'),
            }
        } else {
            output.push(b'?');
        }
    }
    output
}

